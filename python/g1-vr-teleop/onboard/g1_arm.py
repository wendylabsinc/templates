class DataBuffer:
    def __init__(self):
        self.data = None
        self.lock = threading.Lock()

    def GetData(self):
        with self.lock:
            return self.data

    def SetData(self, data):
        with self.lock:
            self.data = data

class G1_29_ArmController:
    def __init__(self, motion_mode=False, simulation_mode=False,
                 record_reading=None, record_lowcmd=None, lowstate_hub=None):
        '''WENDY: `lowstate_hub` (real/lowstate_hub.py) replaces this
        controller's own rt/lowstate reader. Two Python readers of a ~1 kHz
        topic -- this one polling every 2 ms and the onboard's listener
        decoding every sample -- starved the publish loop below of the GIL
        (see lowstate_hub.py). With a hub, the subscribe thread only copies the
        sample the hub already decoded. None keeps the vendored reader.'''
        logger_mp.info("Initialize G1_29_ArmController...")
        self.record_reading = record_reading
        self.record_lowcmd = record_lowcmd
        self.lowstate_hub = lowstate_hub
        self.q_target = np.zeros(14)
        self.waist_yaw_target = None   # WENDY: motor 12 follows only once set
        # The websocket supplies a latest velocity, never repeated position
        # increments. Only the 50 Hz publisher integrates this value, once per
        # motor tick. A stale network command becomes zero locally.
        self.waist_velocity_rad_s = 0.0
        self.waist_velocity_t = 0.0
        self.waist_tick_t = None
        self.waist_velocity_timeout_s = 0.15
        self.waist_velocity_max_rad_s = 0.6
        self.waist_velocity_limits = (-2.5, 2.5)
        self.waist_tracking_error = np.deg2rad(10.0)
        self.waist_velocity_stale = True
        self.waist_velocity_leashed = False
        self.waist_velocity_clamped = False
        self.tauff_target = np.zeros(14)
        self.motion_mode = motion_mode
        self.simulation_mode = simulation_mode
        self.kp_high = 300.0
        self.kd_high = 3.0
        self.kp_low = 80.0
        self.kd_low = 3.0
        self.kp_wrist = 40.0
        self.kd_wrist = 1.5

        self.all_motor_q = None
        # WENDY: was 20.0 here, ramped to 30.0 over 5 s by speed_gradual_max().
        # The ramp is gone (see set_arm_velocity_limit). This final per-cycle
        # clip matches the validated live smoothing range; acceleration,
        # measured-position leash and calibrated joint limits remain the
        # motion-shaping and safety bounds.
        self.set_arm_velocity_limit()
        # WENDY: tunable. The old 250 Hz default exceeded its 4 ms budget and
        # became a busy loop, starving the asyncio receiver. 100 Hz is the
        # qualified target; status exposes achieved cadence and deadline misses.
        # control_dt is also the velocity-clip timebase, so changing it keeps
        # the clip consistent (velocity_limit * control_dt per iteration).
        self.control_dt = 1.0 / float(os.environ.get("G1_CONTROL_HZ", "100"))

        if self.motion_mode:
            self.lowcmd_publisher = ChannelPublisher(kTopicLowCommand_Motion, hg_LowCmd)
        else:
            self.lowcmd_publisher = ChannelPublisher(kTopicLowCommand_Debug, hg_LowCmd)
        self.lowcmd_publisher.Init()
        if self.lowstate_hub is None:
            self.lowstate_subscriber = ChannelSubscriber(kTopicLowState, hg_LowState)
            self.lowstate_subscriber.Init()
        self.lowstate_buffer = DataBuffer()
        # WENDY: filled by the subscribe thread; see get_mode_machine().
        self.mode_machine = None

        # initialize subscribe thread
        # WENDY: stoppable. Upstream it is `while True`, so shutdown() stopped
        # the publisher and left this reader polling rt/lowstate every 2 ms
        # forever -- one more per take_control/relax cycle, each decoding every
        # sample it takes in Python, for the rest of the process's life.
        self._running_subscribe = True
        self.subscribe_thread = threading.Thread(
            target=(self._subscribe_from_hub if self.lowstate_hub is not None
                    else self._subscribe_motor_state))
        self.subscribe_thread.daemon = True
        self.subscribe_thread.start()

        # WENDY: bounded. Upstream this loop is unbounded, and it runs in the
        # CALLER's thread -- so a robot that is not publishing lowstate hung the
        # whole onboard server, /status included, with no way out but a restart.
        # The identical loops in the G1_23 and dual-arm variants below are
        # untouched; we only ever construct this one.
        _deadline = time.time() + 5.0
        while not self.lowstate_buffer.GetData():
            if time.time() > _deadline:
                raise TimeoutError(
                    "no lowstate after 5 s -- is the robot powered and in Main "
                    "Operation Control?")
            time.sleep(0.1)
            logger_mp.warning("[G1_29_ArmController] Waiting to subscribe dds...")
        logger_mp.info("[G1_29_ArmController] Subscribe dds ok.")

        # initialize hg's lowcmd msg
        # The SDK's HG CRC expands a packed 1004-byte command back into 250
        # Python integers and then copies those into ctypes every tick. Keep
        # its exact native crc32_core, but feed it the packed buffer directly.
        # The first command is compared bit-for-bit with the installed SDK;
        # any version/layout mismatch stays on the SDK implementation.
        self.crc = FastHGLowCmdCRC(CRC())
        self.msg = unitree_hg_msg_dds__LowCmd_()
        self.msg.mode_pr = 0
        self.msg.mode_machine = self.get_mode_machine()

        self.all_motor_q = self.get_current_motor_q()
        # Seed before the writer starts; its first command must hold the
        # measured pose, never the constructor's zero-filled placeholder.
        self.q_target = self.get_current_dual_arm_q().copy()
        self.arm_reference = ArmReference(self.q_target)
        self.arm_reference_t = None
        self.arm_position_limits = None
        logger_mp.debug(f"Current all body motor state q:\n{self.all_motor_q} \n")
        logger_mp.debug(f"Current two arms motor state q:\n{self.get_current_dual_arm_q()}\n")
        logger_mp.info("Lock all joints except two arms...")

        arm_indices = set(member.value for member in G1_29_JointArmIndex)
        for id in G1_29_JointIndex:
            self.msg.motor_cmd[id].mode = 1
            if id.value in arm_indices:
                if self._Is_wrist_motor(id):
                    self.msg.motor_cmd[id].kp = self.kp_wrist
                    self.msg.motor_cmd[id].kd = self.kd_wrist
                else:
                    self.msg.motor_cmd[id].kp = self.kp_low
                    self.msg.motor_cmd[id].kd = self.kd_low
            else:
                if self._Is_weak_motor(id):
                    self.msg.motor_cmd[id].kp = self.kp_low
                    self.msg.motor_cmd[id].kd = self.kd_low
                else:
                    self.msg.motor_cmd[id].kp = self.kp_high
                    self.msg.motor_cmd[id].kd = self.kd_high
            self.msg.motor_cmd[id].q  = self.all_motor_q[id]
        logger_mp.info("Lock OK!")

        # initialize publish thread
        self._running = True          # WENDY: see shutdown()
        # WENDY: measured publish rate. The loop targets 1/control_dt (250 Hz);
        # on hardware it was running at ~16, which silently caps how fast the
        # arms can track. Reported so it is visible rather than inferred.
        self.loop_hz = 0.0
        self.loop_worst_ms = 0.0
        self.crc_ms = 0.0          # WENDY: is the CRC the cost, or the write?
        self.write_ms = 0.0
        self.record_ms = 0.0
        self.tick_interval_ms = None
        self.deadlines_missed = 0
        self.affinity = None
        self._loop_n = 0
        self._loop_t0 = None
        self.publish_thread = threading.Thread(target=self._ctrl_motor_state)
        self.ctrl_lock = threading.Lock()
        self.publish_thread.daemon = True
        self.publish_thread.start()

        logger_mp.info("Initialize G1_29_ArmController OK!")

    def _subscribe_motor_state(self):
        while self._running_subscribe:
            msg = self.lowstate_subscriber.Read()
            if msg is not None:
                lowstate = G1_29_LowState()
                for id in range(G1_29_Num_Motors):
                    lowstate.motor_state[id].q  = msg.motor_state[id].q
                    lowstate.motor_state[id].dq = msg.motor_state[id].dq
                # WENDY: mode_machine BEFORE SetData, and the order matters.
                # The constructor's wait gate is `lowstate_buffer.GetData()`,
                # so publishing the buffer first opens that gate one statement
                # before the value it then asks for exists -- the same race
                # this patch removes, just narrower. This way "the buffer has
                # data" implies "mode_machine is set".
                self.mode_machine = msg.mode_machine
                self.lowstate_buffer.SetData(lowstate)
            time.sleep(0.002)

    def _subscribe_from_hub(self):
        '''WENDY: the same copy as _subscribe_motor_state, from the sample the
        onboard's LowstateHub already decoded. Copies only when the hub has a
        NEW sample, so it costs nothing between them. Same ordering rule:
        mode_machine before SetData, so "the buffer has data" implies
        "mode_machine is set".'''
        last_seq = 0
        while self._running_subscribe:
            seq, msg, _t = self.lowstate_hub.latest()
            if msg is not None and seq != last_seq:
                last_seq = seq
                lowstate = G1_29_LowState()
                for id in range(G1_29_Num_Motors):
                    lowstate.motor_state[id].q  = msg.motor_state[id].q
                    lowstate.motor_state[id].dq = msg.motor_state[id].dq
                self.mode_machine = msg.mode_machine
                self.lowstate_buffer.SetData(lowstate)
            time.sleep(0.002)

    def clip_arm_q_target(self, target_q, velocity_limit):
        current_q = self.get_current_dual_arm_q()
        delta = target_q - current_q
        motion_scale = np.max(np.abs(delta)) / (velocity_limit * self.control_dt)
        cliped_arm_q_target = current_q + delta / max(motion_scale, 1.0)
        return cliped_arm_q_target

    def _ctrl_motor_state(self):
        # Isolate the motor publisher on the last available core by default.
        # `G1_MOTOR_CPU=off` restores normal scheduling; an integer selects a
        # specific allowed CPU. This pins only this thread, not aiohttp/DDS.
        self.affinity = pin_current_thread("G1_MOTOR_CPU", default="auto")
        # Pass the module clock explicitly so simulator/tests can supply the
        # same deterministic clock used by the arm reference.
        cadence = DeadlineLoop(self.control_dt, clock=time.monotonic,
                               sleep=time.sleep)
        intervals = deque(maxlen=512)
        previous_start = None
        if self.motion_mode:
            self.msg.motor_cmd[G1_29_JointIndex.kNotUsedJoint0].q = 1.0;

        while self._running:
            start_time = time.monotonic()
            if previous_start is not None:
                intervals.append((start_time - previous_start) * 1000.0)
            previous_start = start_time

            with self.ctrl_lock:
                arm_tauff_target = self.tauff_target.copy()
                if self.simulation_mode:
                    cliped_arm_q_target = self.q_target.copy()
                else:
                    now = time.monotonic()
                    measured = self.get_current_dual_arm_q()
                    if not hasattr(self, "arm_reference"):
                        self.arm_reference = ArmReference(measured)
                        self.arm_reference_t = None
                    previous = self.arm_reference_t
                    dt = self.control_dt if previous is None else now - previous
                    self.arm_reference_t = now
                    cliped_arm_q_target = self.arm_reference.advance(
                        self.q_target, measured, dt,
                        limits=getattr(self, "arm_position_limits", None))
                    self._arm_reference_report = {
                        "q": cliped_arm_q_target.tolist(),
                        "requested_q": self.q_target.tolist(),
                        "velocity": self.arm_reference.velocity.tolist(),
                        "max_velocity_rad_s": self.arm_reference.max_velocity,
                        "max_acceleration_rad_s2": self.arm_reference.max_acceleration,
                        "guard_hits": self.arm_reference.guard_hits,
                        "monotonic_s": now,
                    }

            for idx, id in enumerate(G1_29_JointArmIndex):
                self.msg.motor_cmd[id].q = cliped_arm_q_target[idx]
                self.msg.motor_cmd[id].dq = 0
                self.msg.motor_cmd[id].tau = arm_tauff_target[idx]   
            # WENDY: integrate the latest bounded stick velocity exactly once
            # per LowCmd tick. Network message rate cannot alter distance.
            waist_yaw = self._advance_waist_velocity(
                measured=self.get_current_waist_q(), now=time.monotonic())
            write_waist_cmd(self.msg, waist_yaw)

            _t = time.monotonic()
            self.msg.crc = self.crc.Crc(self.msg)
            _tc = time.monotonic()
            write_result = self.lowcmd_publisher.Write(self.msg)
            _tw = time.monotonic()
            lowcmd_recorder = getattr(self, "record_lowcmd", None)
            crc_values = getattr(self.crc, "last_values", None)
            if lowcmd_recorder is not None and crc_values is not None:
                lowcmd_recorder(crc_values, write_result)
            else:
                recorder = getattr(self, "record_reading", None)
                if recorder is not None:
                    recorder("rt/arm_sdk.write", {"message": self.msg,
                                                   "write_result": write_result})
            _tr = time.monotonic()
            self.crc_ms = round((_tc - _t) * 1000.0, 3)
            self.write_ms = round((_tw - _tc) * 1000.0, 3)
            self.record_ms = round((_tr - _tw) * 1000.0, 3)

            current_time = time.monotonic()
            all_t_elapsed = current_time - start_time
            self.loop_worst_ms = max(self.loop_worst_ms, all_t_elapsed * 1000.0)
            self._loop_n += 1
            if self._loop_t0 is None:
                self._loop_t0 = current_time
            elif current_time - self._loop_t0 >= 1.0:
                self.loop_hz = round(self._loop_n / (current_time - self._loop_t0), 1)
                self._loop_n, self._loop_t0 = 0, current_time
                if intervals:
                    ordered = sorted(intervals)
                    def percentile(fraction):
                        i = min(len(ordered) - 1,
                                max(0, int(np.ceil(len(ordered) * fraction)) - 1))
                        return round(ordered[i], 3)
                    self.tick_interval_ms = {
                        "p50": percentile(0.50), "p95": percentile(0.95),
                        "p99": percentile(0.99), "max": round(ordered[-1], 3),
                    }
                self.loop_worst_ms = 0.0
            cadence.wait()
            self.deadlines_missed = cadence.missed
            # logger_mp.debug(f"arm_velocity_limit:{self.arm_velocity_limit}")
            # logger_mp.debug(f"sleep_time:{sleep_time}")

    def ctrl_dual_arm(self, q_target, tauff_target, waist_yaw=None):
        '''Set control target values q & tau of the left and right arm motors.

        WENDY: `waist_yaw` (radians, motor 12) is optional. None means "leave
        the waist as it is" -- NOT "reset it": the constructor already
        commands motor 12 at its measured angle (rt/arm_sdk carries 12..28,
        and the lock-all-joints loop above writes every motor's q), so the
        waist has been held by this publisher all along. Passing a value
        makes it follow; never passing one changes nothing about today.
        '''
        with self.ctrl_lock:
            self.q_target = np.array(q_target, dtype=float, copy=True)
            self.tauff_target = np.array(tauff_target, dtype=float, copy=True)
            if waist_yaw is not None:
                self.waist_yaw_target = float(waist_yaw)
                self.waist_velocity_rad_s = 0.0
                self.waist_velocity_t = 0.0
                self.waist_tick_t = None

    def arm_reference_report(self):
        with self.ctrl_lock:
            report = dict(getattr(self, "_arm_reference_report", {}))
        if report:
            report["age_s"] = max(0., time.monotonic() - report.pop("monotonic_s"))
        return report or None

    def hold_arm_measured(self):
        """Stop any in-progress reference immediately on HOLD/watchdog."""
        with self.ctrl_lock:
            q = self.get_current_dual_arm_q()
            self.q_target = q.copy()
            self.tauff_target = np.zeros(14)
            self.arm_reference.reset(q)
            self.arm_reference_t = None

    def set_arm_motion_limits(self, limits):
        values = validate_motion_limits(limits)
        with self.ctrl_lock:
            self.arm_reference.max_velocity = values["max_velocity_rad_s"]
            self.arm_reference.max_acceleration = values["max_acceleration_rad_s2"]

    def set_arm_position_limits(self, limits):
        values = np.asarray(limits, dtype=float)
        if values.shape != (14, 2) or not np.all(np.isfinite(values)) or np.any(values[:, 0] >= values[:, 1]):
            raise ValueError("expected 14 finite ordered arm limits")
        with self.ctrl_lock:
            self.arm_position_limits = values.copy()

    def set_waist_target(self, waist_yaw):
        '''Update only motor 12's target for the existing publish loop.

        This does not write DDS and does not create a second motor publisher.
        The same 50 Hz ``_ctrl_motor_state`` loop continues to own the LowCmd;
        the independent waist websocket worker only refreshes this scalar.
        '''
        with self.ctrl_lock:
            self.waist_yaw_target = float(waist_yaw)
            self.waist_velocity_rad_s = 0.0
            self.waist_velocity_t = 0.0
            self.waist_tick_t = None

    def set_waist_velocity(self, velocity, *, limits, tracking_error,
                           timeout_s=0.15, max_velocity=0.6, now=None):
        """Store the newest velocity; never integrate on message arrival."""
        value = float(velocity)
        lo, hi = float(limits[0]), float(limits[1])
        leash = float(tracking_error)
        timeout = float(timeout_s)
        max_speed = float(max_velocity)
        if (not np.isfinite(value) or not np.isfinite(lo) or not np.isfinite(hi)
                or not np.isfinite(leash) or not np.isfinite(timeout)
                or not np.isfinite(max_speed) or lo >= hi or leash <= 0.0
                or timeout <= 0.0 or max_speed <= 0.0):
            raise ValueError("invalid waist velocity configuration")
        value = min(max_speed, max(-max_speed, value))
        stamp = time.monotonic() if now is None else float(now)
        measured = self.get_current_waist_q() if self.waist_yaw_target is None else None
        with self.ctrl_lock:
            if self.waist_yaw_target is None:
                self.waist_yaw_target = measured
                self.waist_tick_t = stamp
            self.waist_velocity_rad_s = value
            self.waist_velocity_t = stamp
            self.waist_velocity_timeout_s = timeout
            self.waist_velocity_max_rad_s = max_speed
            self.waist_velocity_limits = (lo, hi)
            self.waist_tracking_error = leash
            self.waist_velocity_stale = False

    def _advance_waist_velocity(self, measured, now=None):
        """Advance the motor-12 target once. Called only by the publish loop."""
        stamp = time.monotonic() if now is None else float(now)
        measured = float(measured)
        with self.ctrl_lock:
            target = self.waist_yaw_target
            if target is None:
                return None
            previous = self.waist_tick_t
            dt = self.control_dt if previous is None else max(0.0, stamp - previous)
            dt = min(0.05, dt)  # a stalled loop never licenses a position jump
            self.waist_tick_t = stamp
            age = stamp - self.waist_velocity_t
            fresh = 0.0 <= age <= self.waist_velocity_timeout_s
            velocity = self.waist_velocity_rad_s if fresh else 0.0
            lo, hi = self.waist_velocity_limits
            asked = float(target) + float(velocity) * dt
            bounded = min(hi, max(lo, asked))
            self.waist_velocity_clamped = bounded != asked
            leash_lo = measured - self.waist_tracking_error
            leash_hi = measured + self.waist_tracking_error
            leashed = min(leash_hi, max(leash_lo, bounded))
            self.waist_velocity_leashed = leashed != bounded
            self.waist_velocity_stale = not fresh
            self.waist_yaw_target = leashed
            return leashed

    def waist_control_state(self):
        with self.ctrl_lock:
            return {
                "target": self.waist_yaw_target,
                "velocity": self.waist_velocity_rad_s,
                "stale": self.waist_velocity_stale,
                "leashed": self.waist_velocity_leashed,
                "clamped": self.waist_velocity_clamped,
            }

    def stop_waist_velocity(self, *, hold_measured=True):
        """Stop rate control immediately; HOLD may reseed at measured pose."""
        measured = self.get_current_waist_q() if hold_measured else None
        with self.ctrl_lock:
            self.waist_velocity_rad_s = 0.0
            self.waist_velocity_t = 0.0
            self.waist_velocity_stale = True
            self.waist_tick_t = time.monotonic()
            if measured is not None:
                self.waist_yaw_target = float(measured)

    def get_mode_machine(self):
        '''Return the robot's mode_machine as last seen on rt/lowstate.

        WENDY: this used to be `self.lowstate_subscriber.Read().mode_machine`,
        as upstream had it. Read() hands out each queued sample once, and the
        subscribe thread is draining that same queue every 2 ms -- so the
        constructor's one call raced the thread for the next sample and got
        None whenever the thread won: `AttributeError: 'NoneType' object has
        no attribute 'mode_machine'`, at startup, only sometimes. The thread
        now records the value as it reads, and this refuses rather than
        guesses when nothing has arrived yet. Unitree made the same change
        upstream (xr_teleoperate 6738633, 2026-08-03).
        '''
        if self.mode_machine is None:
            raise RuntimeError("G1 low state is not ready.")
        return self.mode_machine

    def get_current_motor_q(self):
        '''Return current state q of all body motors.'''
        return np.array([self.lowstate_buffer.GetData().motor_state[id].q for id in G1_29_JointIndex])
    
    def get_current_dual_arm_q(self):
        '''Return current state q of the left and right arm motors.'''
        return np.array([self.lowstate_buffer.GetData().motor_state[id].q for id in G1_29_JointArmIndex])

    def get_current_waist_q(self):
        '''Return the newest waist-yaw position without another DDS read.'''
        return float(self.lowstate_buffer.GetData().motor_state[12].q)
    
    def get_current_dual_arm_dq(self):
        '''Return current state dq of the left and right arm motors.'''
        return np.array([self.lowstate_buffer.GetData().motor_state[id].dq for id in G1_29_JointArmIndex])
    
    def ctrl_dual_arm_go_home(self):
        '''Move both the left and right arms of the robot to their home position by setting the target joint angles (q) and torques (tau) to zero.'''
        logger_mp.info("[G1_29_ArmController] ctrl_dual_arm_go_home start...")
        max_attempts = 100
        current_attempts = 0
        with self.ctrl_lock:
            self.q_target = np.zeros(14)
            # self.tauff_target = np.zeros(14)
        tolerance = 0.05  # Tolerance threshold for joint angles to determine "close to zero", can be adjusted based on your motor's precision requirements
        while current_attempts < max_attempts:
            current_q = self.get_current_dual_arm_q()
            if np.all(np.abs(current_q) < tolerance):
                if self.motion_mode:
                    for weight in np.linspace(1, 0, num=101):
                        self.msg.motor_cmd[G1_29_JointIndex.kNotUsedJoint0].q = weight;
                        time.sleep(0.02)
                logger_mp.info("[G1_29_ArmController] both arms have reached the home position.")
                break
            current_attempts += 1
            time.sleep(0.05)

    def set_arm_compliance(self, kp = None, kd = None):
        """WENDY: make ONLY the arm joints soft, so they can be posed by hand.

        The alternative is the robot's own damping mode, which limps the legs
        too and drops 35 kg where it stands. We hold arm_sdk, so we can zero the
        arm gains and leave the legs with the balance controller.

        kp=None restores the init gains. With kp=0 the arms are back-drivable
        but have NO gravity compensation, so they sag -- kd damps that into a
        slow settle rather than a flop.
        """
        for id in G1_29_JointArmIndex:
            if kp is None:
                if self._Is_wrist_motor(id):
                    self.msg.motor_cmd[id].kp = self.kp_wrist
                    self.msg.motor_cmd[id].kd = self.kd_wrist
                else:
                    self.msg.motor_cmd[id].kp = self.kp_low
                    self.msg.motor_cmd[id].kd = self.kd_low
            else:
                self.msg.motor_cmd[id].kp = float(kp)
                self.msg.motor_cmd[id].kd = float(kd if kd is not None else 1.0)

    # WENDY: per-joint gains, for the jog panel. idx is 0..13 in
    # G1_29_JointArmIndex order (the same 14-vector everything else speaks).
    # Bounds are enforced by the caller (g1_onboard.Commander.set_gains); this
    # only writes the message, under the same lock the publish loop reads it.
    def set_joint_gains(self, idx, kp, kd):
        jid = list(G1_29_JointArmIndex)[int(idx)]
        with self.ctrl_lock:
            self.msg.motor_cmd[jid].kp = float(kp)
            self.msg.motor_cmd[jid].kd = float(kd)

    def get_gains(self):
        """-> [(kp, kd)] x 14, what the wire currently carries."""
        return [(float(self.msg.motor_cmd[j].kp), float(self.msg.motor_cmd[j].kd))
                for j in G1_29_JointArmIndex]

    def default_gains(self):
        """-> [(kp, kd)] x 14, the constructor's values."""
        return [(self.kp_wrist, self.kd_wrist) if self._Is_wrist_motor(j)
                else (self.kp_low, self.kd_low) for j in G1_29_JointArmIndex]

    def shutdown(self, ramp_s = 1.0):
        """Stop publishing and hand rt/arm_sdk back to the motion controller.

        WENDY: upstream has no way to stop this. _ctrl_motor_state is a bare
        `while True` in a daemon thread, so dropping the Python reference to the
        controller left it publishing weight 1.0 on all 29 joints FOREVER.
        "Release" therefore never released: the robot's own controller fought
        those stale commands on every subsequent mode change, and a second
        take_control would have added a second publisher to the same topic.
        Measured on hardware -- STANDBY with rt/arm_sdk still at 28 Hz, weight
        1.0 -- and it is what a grinding noise sounds like.

        The weight is ramped rather than dropped: going from 1 to 0 in one step
        is a step change in who owns the joints.
        """
        try:
            if self.motion_mode:
                steps = max(1, int(ramp_s / self.control_dt))
                for w in np.linspace(1.0, 0.0, steps):
                    self.msg.motor_cmd[G1_29_JointIndex.kNotUsedJoint0].q = float(w)
                    time.sleep(self.control_dt)
        finally:
            # Must happen even if the ramp raises, or the thread outlives us
            # again -- which is the whole bug.
            self._running = False
            t = getattr(self, "publish_thread", None)
            if t is not None and t.is_alive():
                t.join(timeout=2.0)
            # And the reader, for the same reason (see __init__). It may be
            # blocked in Read() until the next sample; it exits on that one.
            self._running_subscribe = False
            s = getattr(self, "subscribe_thread", None)
            if s is not None and s.is_alive():
                s.join(timeout=0.5)

    def set_arm_velocity_limit(self, velocity_limit = 50.0):
        '''Set the per-cycle velocity clip on the arm joints, in rad/s.

        WENDY: replaces speed_gradual_max()/speed_instant_max(), which ramped
        from 20 to 30 rad/s over 5 s after arming. The motor-clock reference
        owns the live velocity and acceleration caps; this downstream clip is
        only a final ceiling and must not undercut the validated 50 rad/s
        tuning range. Same fixed-clip shape Unitree made upstream
        (xr_teleoperate 4cbf6e2).
        '''
        velocity_limit = float(velocity_limit)
        if not np.isfinite(velocity_limit) or velocity_limit <= 0.0:
            raise ValueError("arm_velocity_limit must be a positive finite value.")
        self.arm_velocity_limit = velocity_limit

